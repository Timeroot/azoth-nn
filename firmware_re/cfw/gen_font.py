def art(rows):
    assert len(rows) == 8, rows
    out = []
    for r in rows:
        r = (r + "........")[:8]
        b = 0
        for c, ch in enumerate(r):
            if ch not in ".": b |= (1 << c)
        out.append(b)
    return out

