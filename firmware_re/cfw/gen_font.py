PUNCT_ORDER = list('!"#$%&\'()*+,-./' ':;<=>?@' '[\\]^_`' '{|}~')

def main():
    font = [None]*72
    for i in range(26):
        font[i] = LETTERS[i*8:i*8+8]
    for i, d in enumerate("0123456789"):
        font[26+i] = art(DIGITS[d])
    for tok in (36,37,38,39):
        font[tok] = art(MARK[tok])
    for i, ch in enumerate(PUNCT_ORDER):
        font[40+i] = art(PUNCT[ch])
    assert all(f is not None for f in font)
    # emit C
    lines = []
    labels = ([chr(ord('a')+i) for i in range(26)] + list("0123456789")
              + ["space","tab","newline","CAPESC"] + PUNCT_ORDER)
    for i in range(72):
        vals = ",".join(f"0x{b:02X}" for b in font[i])
        lines.append(f"{{{vals}}}, /* {i:2d} {labels[i]} */")
    print("static const uint8_t FONT[72][8] = {")
    for ln in lines: print("  " + ln)
    print("};")

if __name__ == "__main__":
    main()
