/* 3 bouncing letters (init A,H,M). Reading the live HID report, each new
 * alphabetic keypress replaces one slot, cycling 0->1->2. Validates on-device
 * keystroke capture + a font blitter. Rides the flush detour (render(fb,len)). */
#include <stdint.h>

#define STRIDE   0x80u
#define CNT      ((volatile uint32_t*)0x2003f000u)   /* free RAM above SP  */
#define MAGIC    0xBA11B012u
#define DIRTY    (*(volatile uint8_t*)0x200034bau)     /* content-changed    */
#define RPTCNT   (*(volatile uint32_t*)0x20003370u)    /* HID report key cnt */
#define RPT      ((volatile uint16_t*)0x2000b6f8u)     /* HID report array   */

/* RAM layout (uint32 indices into CNT): 0=t 1=magic 2=cycle 3=last_seen */
#define SLOTS    ((volatile uint8_t*)0x2003f010u)      /* 3 glyph indices    */

/* classic 8x8 font (public domain, Hepper font8x8_basic), A-Z; bit0 = leftmost */
static const uint8_t FONT[26][8] = {
{0x0C,0x1E,0x33,0x33,0x3F,0x33,0x33,0x00},{0x3F,0x66,0x66,0x3E,0x66,0x66,0x3F,0x00},
{0x3C,0x66,0x03,0x03,0x03,0x66,0x3C,0x00},{0x1F,0x36,0x66,0x66,0x66,0x36,0x1F,0x00},
{0x7F,0x46,0x16,0x1E,0x16,0x46,0x7F,0x00},{0x7F,0x46,0x16,0x1E,0x16,0x06,0x0F,0x00},
{0x3C,0x66,0x03,0x03,0x73,0x66,0x7C,0x00},{0x33,0x33,0x33,0x3F,0x33,0x33,0x33,0x00},
{0x1E,0x0C,0x0C,0x0C,0x0C,0x0C,0x1E,0x00},{0x78,0x30,0x30,0x30,0x33,0x33,0x1E,0x00},
{0x67,0x66,0x36,0x1E,0x36,0x66,0x67,0x00},{0x0F,0x06,0x06,0x06,0x46,0x66,0x7F,0x00},
{0x63,0x77,0x7F,0x7F,0x6B,0x63,0x63,0x00},{0x63,0x67,0x6F,0x7B,0x73,0x63,0x63,0x00},
{0x1C,0x36,0x63,0x63,0x63,0x36,0x1C,0x00},{0x3F,0x66,0x66,0x3E,0x06,0x06,0x0F,0x00},
{0x1E,0x33,0x33,0x33,0x3B,0x1E,0x38,0x00},{0x3F,0x66,0x66,0x3E,0x36,0x66,0x67,0x00},
{0x1E,0x33,0x07,0x0E,0x38,0x33,0x1E,0x00},{0x3F,0x2D,0x0C,0x0C,0x0C,0x0C,0x1E,0x00},
{0x33,0x33,0x33,0x33,0x33,0x33,0x3F,0x00},{0x33,0x33,0x33,0x33,0x33,0x1E,0x0C,0x00},
{0x63,0x63,0x63,0x6B,0x7F,0x77,0x63,0x00},{0x63,0x63,0x36,0x1C,0x1C,0x36,0x63,0x00},
{0x33,0x33,0x33,0x1E,0x0C,0x0C,0x1E,0x00},{0x7F,0x63,0x31,0x18,0x4C,0x66,0x7F,0x00},
};

static uint32_t tri(uint32_t p, uint32_t M) { uint32_t two=2u*M; p%=two; if(p>=M)p=two-p; return p; }

static void setpx(uint8_t *fb, uint32_t x, uint32_t y, uint8_t nib) {
    uint8_t *p = fb + y*STRIDE + (x>>1);
    if (x & 1) *p = (*p & 0x0F) | (nib<<4);
    else       *p = (*p & 0xF0) | nib;
}

/* draw glyph at (px,py), scale 2 -> 16x16, nibble colour */
static void draw_char(uint8_t *fb, uint32_t px, uint32_t py, uint32_t g, uint8_t nib) {
    for (uint32_t row=0; row<8; row++) {
        uint8_t bits = FONT[g][row];
        for (uint32_t c=0; c<8; c++) {
            if ((bits>>c) & 1) {
                uint32_t x0=px+c*2, y0=py+row*2;
                setpx(fb,x0,y0,nib);   setpx(fb,x0+1,y0,nib);
                setpx(fb,x0,y0+1,nib); setpx(fb,x0+1,y0+1,nib);
            }
        }
    }
}

__attribute__((section(".text.render"), used))
void render(uint8_t *fb, int len) {
    (void)len;
    if (CNT[1] != MAGIC) {                       /* first run: init state */
        CNT[0]=0; CNT[1]=MAGIC; CNT[2]=0; CNT[3]=0xFF;
        SLOTS[0]=0; SLOTS[1]=7; SLOTS[2]=12;     /* A, H, M */
    }
    uint32_t t = (CNT[0]+1u) & 0xFFFFu; CNT[0]=t;
    DIRTY = 1;

    /* ---- read live HID report, edge-detect a new letter ---- */
    int found = -1;
    uint32_t n = RPTCNT; if (n > 0x78u) n = 0x78u;
    for (uint32_t i=0; i<n; i++) {
        uint16_t kc = RPT[i];
        if (kc >= 0x04 && kc <= 0x1d) { found = (int)(kc - 0x04); break; }
    }
    if (found >= 0) {
        if ((uint32_t)found != CNT[3]) {          /* new press */
            SLOTS[CNT[2]] = (uint8_t)found;
            CNT[2] = (CNT[2]+1u) % 3u;
            CNT[3] = (uint32_t)found;
        }
    } else {
        CNT[3] = 0xFF;                             /* nothing held -> allow repeats */
    }

    /* ---- draw ---- */
    uint32_t *p=(uint32_t*)fb; for(int i=0;i<0x2000/4;i++) p[i]=0;
    draw_char(fb, tri(t*2u,      240), tri(t,       48), SLOTS[0], 0xF);
    draw_char(fb, tri(t+80u,     240), tri(t*3u+20u,48), SLOTS[1], 0xA);
    draw_char(fb, tri(t*3u+160u, 240), tri(t*2u+40u,48), SLOTS[2], 0x6);
}
