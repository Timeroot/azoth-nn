/* Flash-ceiling finder. The whole region [0x4e000, ...) is filled with marker 0x5A
 * at build time; the bootloader writes it up to the ceiling and drops the rest
 * (leaving 0xFF). This scans for the first 0xFF byte and prints its address (hex)
 * on the OLED = the exact writable ceiling. Rides the flush detour (render). */
#include <stdint.h>
#define STRIDE 0x80u
#define DIRTY  (*(volatile uint8_t*)0x200034bau)

