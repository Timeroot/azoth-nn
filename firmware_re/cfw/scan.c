static void setpx(uint8_t*fb,uint32_t x,uint32_t y,uint8_t nib){
    uint8_t*p=fb+y*STRIDE+(x>>1); if(x&1)*p=(*p&0x0F)|(nib<<4); else *p=(*p&0xF0)|nib; }
static void draw_char(uint8_t*fb,uint32_t px,uint32_t py,uint32_t g,uint8_t nib,uint32_t s){
    for(uint32_t row=0;row<8;row++){ uint8_t bits=FONT[g][row];
        for(uint32_t c=0;c<8;c++) if((bits>>c)&1){ uint32_t x0=px+c*s,y0=py+row*s;
            for(uint32_t a=0;a<s;a++) for(uint32_t b=0;b<s;b++) setpx(fb,x0+a,y0+b,nib);} } }
static void draw_hexdig(uint8_t*fb,uint32_t px,uint32_t py,uint32_t nib4,uint8_t col,uint32_t s){
    uint32_t g = (nib4<10)? (32u+nib4) : (nib4-10u);   /* 0-9 -> digits, A-F -> glyphs 0-5 */
    draw_char(fb,px,py,g,col,s);
}

__attribute__((section(".text.render"), used))
void render(uint8_t *fb, int len){
    (void)len; DIRTY=1;
    /* find first 0xFF byte at/after 0x4e000 = writable ceiling */
    uint32_t a=0x4e000u;
    while(a<0x100000u && *(volatile uint8_t*)a == 0x5Au) a++;   /* first non-marker = ceiling */

    uint32_t *pp=(uint32_t*)fb; for(int i=0;i<0x2000/4;i++) pp[i]=0;
    /* label "END" then the address, 6 hex digits */
    draw_char(fb, 4, 4, 4, 0x8, 2); draw_char(fb,20,4,13,0x8,2); draw_char(fb,36,4,3,0x8,2);
    for(int d=0; d<6; d++){
        uint32_t nib = (a >> ((5-d)*4)) & 0xFu;
        draw_hexdig(fb, 8 + d*40, 24, nib, 0xF, 4);
    }
}
